// Exercises the compiled WebAssembly engine, not a replacement JavaScript game.
const assert = require('node:assert/strict');
const path = require('node:path');
const { performance } = require('node:perf_hooks');
const { BrowserGame } = require(path.join(path.resolve(process.argv[2]), 'termcraft.js'));
const columns = 200, rows = 60;
let game = new BrowserGame(columns, rows);
const status = () => JSON.parse(game.status());
function steps(count) { for(let i=0;i<count;i++) game.frame(50); }
const first = game.frame(0);
assert.equal(first.length,columns*rows*3);
assert(new Set(first).size>150,'expected the actual coloured game renderer');
const initial = status();
game.key('KeyD',true,false); game.key('KeyD',false,false); steps(1);
assert(status().x>initial.x,'a tap shorter than one tick must still move');
game.release_controls(); steps(5);
game.key('KeyD',true,false); steps(8);
const walking = status();
assert(walking.x>initial.x+1,'walking must advance');
game.key('Space',true,false); steps(2);
assert(status().y<walking.y-0.3,'jumping while moving must leave the ground');
game.key('Space',false,false); game.key('KeyD',false,false); steps(18);
game.release_controls(); steps(8);
const stopped = status();steps(8);
assert(Math.abs(status().x-stopped.x)<0.05,'released movement must stop');
game.key('KeyE',true,false);assert.equal(status().inventory_open,true);
assert.equal(game.key('Escape',true,false),false,'Escape closes inventory first');
assert.equal(status().inventory_open,false);
assert.equal(game.key('Escape',true,false),true,'Escape then pauses');
const beforeSave = status();
const snapshot = game.snapshot();
const saved = JSON.parse(snapshot);
assert.equal(saved.format,'termcraft-browser');
assert(Object.keys(saved.files).some(name=>name.endsWith('player_progression.bin')),'player checkpoint must be present');
assert(Object.keys(saved.files).some(name=>name.endsWith('overworld_chunk_0.bin')),'terrain must be present');
game.free();game=new BrowserGame(columns,rows,snapshot);
assert(Math.abs(status().x-beforeSave.x)<0.001,'restore player x');
assert(Math.abs(status().y-beforeSave.y)<0.001,'restore player y');
assert.equal(status().health,beforeSave.health,'restore health');
game.frame(0);
game.free();
assert.throws(()=>new BrowserGame(columns,rows,'{}'),'reject invalid imported saves');
assert.throws(()=>new BrowserGame(columns,rows,JSON.stringify({...saved,version:99})),'reject future browser save formats');
assert.throws(()=>new BrowserGame(columns,rows,JSON.stringify({...saved,files:{'':null,'../escape':[1]}})),'reject path traversal');
const corrupt = JSON.parse(snapshot);
const playerFile = Object.keys(corrupt.files).find(name=>name.endsWith('/player_progression.bin')&&!name.includes('.world-checkpoint'));
corrupt.files[playerFile] = [1,2,3];
assert.throws(()=>new BrowserGame(columns,rows,JSON.stringify(corrupt)),'corrupt player data must not silently create a new world');
game=new BrowserGame(columns,rows,snapshot);
const started=performance.now();steps(100);
const msPerTick=(performance.now()-started)/100;
game.free();

// Natural worlds must use native generation, never a flattened trial recipe.
game=new BrowserGame(columns,rows,undefined,'survival');
assert.equal(status().mode,'survival');
assert.equal(status().dimension,'Overworld');
assert.equal(status().health,20);
assert.equal(game.frame(0).length,columns*rows*3);
const naturalStatus=status();
const naturalSnapshot=game.snapshot();
const naturalFiles=JSON.parse(naturalSnapshot).files;
const seedPath='saves/survival/overworld_world_seed.bin';
assert.equal(naturalFiles[seedPath].length,16,'four native generator seeds');
assert(!Object.keys(naturalFiles).some(name=>name.endsWith('/world.json')||name.endsWith('/lantern-trial.json')),'natural terrain must not use a custom map recipe');
assert(Object.keys(naturalFiles).some(name=>name.startsWith('saves/survival/overworld_chunk_')),'native chunks are saved');
game.free();
// Import identifies its own mode rather than silently changing the terrain.
game=new BrowserGame(columns,rows,naturalSnapshot,'lantern-run');
assert.equal(status().mode,'survival');
assert.equal(status().x,naturalStatus.x);
assert.equal(status().y,naturalStatus.y);
assert.deepEqual(JSON.parse(game.snapshot()).files[seedPath],naturalFiles[seedPath]);
game.free();
game=new BrowserGame(columns,rows,undefined,'survival');
assert.notDeepEqual(JSON.parse(game.snapshot()).files[seedPath],naturalFiles[seedPath],'New survival world must generate fresh seeds');
game.free();
game=new BrowserGame(columns,rows,snapshot,'survival');
assert.equal(status().mode,'lantern-run','legacy Lantern Run saves remain playable');
assert(Math.abs(status().x-beforeSave.x)<0.001);
game.free();
const badSeed=JSON.parse(naturalSnapshot);badSeed.files[seedPath]=[1,2,3];
assert.throws(()=>new BrowserGame(columns,rows,JSON.stringify(badSeed)),'corrupt natural seed must not be regenerated');
assert.throws(()=>new BrowserGame(columns,rows,undefined,'unknown'),'reject invalid world modes');
console.log(JSON.stringify({status:'passed',real_wasm_engine:true,movement_and_jump:true,release_stops:true,inventory_controls:true,save_roundtrip:true,invalid_imports_rejected:true,native_world_generation:true,fresh_seeds:true,legacy_trial_restore:true,frame_cells:columns*rows,render_and_tick_ms:Math.round(msPerTick*100)/100}));
